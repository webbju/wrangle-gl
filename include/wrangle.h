#if defined(__linux__)
#include <dlfcn.h>
static void *dlGetProcAddress (const char *library, const char *symbol)
{
  static void *image = nullptr;
  void *addr = nullptr;
  if (image == nullptr)
  {
    image = dlopen (library, RTLD_LAZY);
  }
  if (image != nullptr)
  {
    addr = dlsym (image, symbol);
  }
  return addr;
}
#endif

